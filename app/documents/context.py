"""Русские названия месяцев и мелкие хелперы форматирования для документов."""
from __future__ import annotations

from datetime import date

_MONTHS_GEN = {
    1: "января", 2: "февраля", 3: "марта", 4: "апреля", 5: "мая", 6: "июня",
    7: "июля", 8: "августа", 9: "сентября", 10: "октября", 11: "ноября", 12: "декабря",
}
_MONTHS_NOM = {
    1: "январь", 2: "февраль", 3: "март", 4: "апрель", 5: "май", 6: "июнь",
    7: "июль", 8: "август", 9: "сентябрь", 10: "октябрь", 11: "ноябрь", 12: "декабрь",
}


def date_ru(d: date) -> str:
    """Дата вида «30 апреля 2026 г.»."""
    return f"{d.day} {_MONTHS_GEN[d.month]} {d.year} г."


def date_dmy(d: date) -> str:
    """Дата вида «30.04.2026»."""
    return d.strftime("%d.%m.%Y")


def period_ru(d: date) -> str:
    """Период вида «апрель 2026 г.»."""
    return f"{_MONTHS_NOM[d.month]} {d.year} г."
